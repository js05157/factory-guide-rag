"""2단계 — Streamlit의 유일한 규칙: 무슨 일이 생기면 처음부터 다시 실행된다.        ✏️ 실습용

실행:
    streamlit run step2_rerun.py

1단계에서 이름을 바꾸자 인사말이 사라졌습니다. 그 이유를 여기서 봅니다.

[실습 1]을 채운 뒤, 버튼을 누르기 전에 먼저 예상해 보세요. 다섯 번 누르면 count는 몇이 될까요?

비유      — 칠판을 다 지우고 처음부터 다시 쓰는 선생님. 버튼을 누를 때마다 파일 첫 줄부터 다시 씁니다.
한 걸음 더 — 요청이 올 때마다 메서드가 처음부터 도는 웹 컨트롤러(예: Spring)와 같습니다.
             메서드 안의 지역 변수는 요청이 끝나면 사라집니다. 모바일·React의 "상태가 바뀌면 화면을
             다시 그린다(UI = f(state))"와도 닮았습니다.
"""

import time

import streamlit as st

st.title("2단계 — 다시 실행되는 것을 눈으로 보기")

# 이 줄은 화면이 바뀔 때마다 실행된다.
st.write("이 스크립트가 실행된 시각:", time.strftime("%H:%M:%S"))

# [실습 1] 세 줄이면 됩니다.
#          ① count 를 0으로 둔다.
#          ② st.button("눌러 보세요") 가 눌렸으면 count 를 1 올린다.
#          ③ st.write("count =", count) 로 화면에 쓴다.

count = 0
if st.button("눌러보세요"):
    count += 1

st.write("count= ", count)


with st.expander("다섯 번 눌러 본 뒤에 펼쳐 보세요"):
    st.info(
        "버튼을 눌러도 count가 1을 넘지 못합니다.\n\n"
        "버튼을 누르면 **파일 첫 줄부터 다시 실행**되고, `count = 0`을 또 지나가기 때문입니다.\n\n"
        "시각도 매번 바뀌는 것을 보세요. 1단계의 인사말이 사라진 것도 같은 이유입니다."
    )
